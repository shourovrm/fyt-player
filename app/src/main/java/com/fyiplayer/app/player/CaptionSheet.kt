/**
 * Caption-track picker for the item currently playing -- same shape as [QualitySheet]. [tracks] is
 * [PlaybackSession.state]'s `availableCaptions`, so this can never offer a track the current item
 * didn't actually publish. "Off" is first and matches [selectedLanguage] null (captions start OFF
 * by project rule); [onSelect] null means Off, a track means
 * [PlaybackSession.selectCaption]. [CaptionTrack.label] already carries "(auto)" for
 * auto-generated tracks, so it is shown verbatim, never re-derived from [CaptionTrack.autoGenerated].
 *
 * [captionSize] is the caller's own pref (video or Shorts), and [onCaptionSizeSelect] writes it
 * back to that same pref, so this sheet and Settings always show one value.
 */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun CaptionSheet(
    tracks: List<CaptionTrack>,
    selectedLanguage: String?,
    onSelect: (CaptionTrack?) -> Unit,
    captionSize: CaptionSize,
    onCaptionSizeSelect: (CaptionSize) -> Unit,
    onDismiss: () -> Unit,
) {
    ModalBottomSheet(onDismissRequest = onDismiss) {
        LazyColumn(modifier = Modifier.padding(bottom = Spacing.s16)) {
            item {
                ListItem(
                    headlineContent = { Text(stringResource(R.string.player_captions_off)) },
                    leadingContent = { RadioButton(selected = selectedLanguage == null, onClick = { onSelect(null) }) },
                    modifier = Modifier.clickable { onSelect(null) },
                )
            }
            items(tracks, key = { it.languageCode + it.label }) { track ->
                ListItem(
                    headlineContent = { Text(track.label) },
                    leadingContent = {
                        RadioButton(selected = track.languageCode == selectedLanguage, onClick = { onSelect(track) })
                    },
                    modifier = Modifier.clickable { onSelect(track) },
                )
            }
            item {
                Text(
                    stringResource(R.string.caption_size_chips_label),
                    style = MaterialTheme.typography.labelLarge,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                    modifier = Modifier.padding(start = Spacing.pageMargin, top = Spacing.s16, end = Spacing.pageMargin, bottom = Spacing.s8),
                )
            }
            item {
                // A scrolling row, not a wrapping one: four labels such as "Extra large" fit on
                // most phones, and on a narrow one the last chip scrolls into view instead of clipping.
                LazyRow(
                    contentPadding = PaddingValues(horizontal = Spacing.pageMargin),
                    horizontalArrangement = Arrangement.spacedBy(Spacing.s8),
                ) {
                    items(CaptionSize.entries, key = { it.name }) { size ->
                        FilterChip(
                            selected = size == captionSize,
                            onClick = { onCaptionSizeSelect(size) },
                            label = { Text(captionSizeLabel(size)) },
                        )
                    }
                }
            }
        }
    }
}

/** The shared wording for a [CaptionSize] step, so the sheet chips and the Settings segments match. */
@Composable
internal fun captionSizeLabel(size: CaptionSize): String = stringResource(
    when (size) {
        CaptionSize.SMALL -> R.string.caption_size_small
        CaptionSize.MEDIUM -> R.string.caption_size_medium
        CaptionSize.LARGE -> R.string.caption_size_large
        CaptionSize.EXTRA_LARGE -> R.string.caption_size_extra_large
    },
)
