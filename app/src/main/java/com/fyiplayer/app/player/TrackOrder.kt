package com.fyiplayer.app.player

import com.fyiplayer.app.core.CaptionTrack
import com.fyiplayer.app.core.MediaFormat
import java.util.Locale

/*
 * Picker order for caption and audio tracks. The platform lists them sorted by English language
 * name but labels each in its own language ("Deutsch" between "English" and "français"), which
 * reads as no order at all. Here: the video's original language first, then labels in Latin
 * letters A to Z, then other scripts A to Z, both by English name. Captions also put
 * human-written tracks before automatic ones.
 */

/**
 * The language spoken in the video, as a primary language code ("en"), or null when unknown. The
 * audio track the platform flags as original says it directly. Without one, a single automatic
 * caption track does: automatic captions are made from the speech. More than one automatic track
 * (translations) gives no answer rather than a guess.
 */
fun originalLanguageOf(formats: List<MediaFormat>, captions: List<CaptionTrack>): String? {
    formats.firstOrNull { it.isOriginalAudio }?.audioLanguage?.let { return primaryLanguage(it) }
    val automatic = captions.filter { it.autoGenerated }
    return automatic.singleOrNull()?.let { primaryLanguage(it.languageCode) }
}

/** Original language first (written before automatic), then written tracks, then automatic ones. */
fun orderCaptions(captions: List<CaptionTrack>, formats: List<MediaFormat>): List<CaptionTrack> {
    val original = originalLanguageOf(formats, captions)
    val (originalTracks, others) = captions.partition { original != null && primaryLanguage(it.languageCode) == original }
    val (written, automatic) = others.partition { !it.autoGenerated }
    val byName = trackComparator<CaptionTrack>({ it.languageCode }, { it.label })
    return originalTracks.sortedBy { it.autoGenerated } + written.sortedWith(byName) + automatic.sortedWith(byName)
}

/** Original audio first, then the rest in the same Latin-then-other-scripts order. */
fun orderAudioFormats(formats: List<MediaFormat>): List<MediaFormat> {
    val (original, others) = formats.partition { it.isOriginalAudio }
    return original + others.sortedWith(trackComparator({ it.audioLanguage }, { it.audioLabel ?: it.audioTrackId.orEmpty() }))
}

/** Latin-script labels before other scripts; within each, by English language name, then label. */
private fun <T> trackComparator(language: (T) -> String?, label: (T) -> String): Comparator<T> =
    compareBy<T> { !isLatinScript(label(it)) }
        .thenBy(String.CASE_INSENSITIVE_ORDER) { englishName(language(it), label(it)) }
        .thenBy { label(it) }

/** "en-US" and "en" are the same spoken language. */
private fun primaryLanguage(code: String): String = Locale.forLanguageTag(code).language.ifEmpty { code }

/** "de" -> "German". Falls back to [label] when the code names no language Java knows. */
internal fun englishName(code: String?, label: String): String {
    if (code == null) return label
    return Locale.forLanguageTag(code).getDisplayLanguage(Locale.ENGLISH).ifEmpty { label }
}

/** Judged by the first letter, so "(auto)" and digits in a label do not count. */
internal fun isLatinScript(label: String): Boolean {
    val firstLetter = label.codePoints().filter(Character::isLetter).findFirst()
    if (!firstLetter.isPresent) return true
    return Character.UnicodeScript.of(firstLetter.asInt) == Character.UnicodeScript.LATIN
}
