package com.fyiplayer.app.player

import com.fyiplayer.app.core.CaptionTrack
import com.fyiplayer.app.core.MediaFormat
import com.fyiplayer.app.core.Protocol
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

private fun caption(code: String, label: String, auto: Boolean = false) =
    CaptionTrack(url = "https://example.invalid/$code", mimeType = "text/vtt", languageCode = code, label = label, autoGenerated = auto)

private fun audio(code: String, label: String, original: Boolean = false) = MediaFormat(
    formatId = code, url = "https://example.invalid/$code", container = "webm", protocol = Protocol.PROGRESSIVE,
    audioCodec = "opus", audioTrackId = "$code.0", audioLanguage = code, audioLabel = label, isOriginalAudio = original,
)

class TrackOrderTest {

    @Test fun `latin script is judged by the first letter`() {
        assertTrue(isLatinScript("Deutsch (auto)"))
        assertTrue(isLatinScript("español"))
        assertFalse(isLatinScript("العربية (auto)"))
        assertFalse(isLatinScript("日本語"))
    }

    @Test fun `english name comes from the code, else the label`() {
        assertEquals("German", englishName("de", "Deutsch"))
        assertEquals("Deutsch", englishName(null, "Deutsch"))
    }

    @Test fun `original language is the audio track flagged original`() {
        val formats = listOf(audio("es", "Spanish"), audio("en-US", "English", original = true))
        assertEquals("en", originalLanguageOf(formats, emptyList()))
    }

    @Test fun `original language falls back to the one automatic caption track`() {
        val captions = listOf(caption("de", "Deutsch"), caption("fr", "français (auto)", auto = true))
        assertEquals("fr", originalLanguageOf(emptyList(), captions))
    }

    @Test fun `several automatic tracks give no original language`() {
        val captions = listOf(caption("de", "Deutsch (auto)", auto = true), caption("fr", "français (auto)", auto = true))
        assertNull(originalLanguageOf(emptyList(), captions))
    }

    @Test fun `captions go original, written latin, written other, automatic latin, automatic other`() {
        val captions = listOf(
            caption("ar", "العربية (auto)", auto = true),
            caption("bn", "বাংলা"),
            caption("nl", "Nederlands (auto)", auto = true),
            caption("en", "English (auto)", auto = true),
            caption("en", "English"),
            caption("de", "Deutsch"),
            caption("ja", "日本語 (auto)", auto = true),
            caption("es", "español"),
            caption("ar", "العربية"),
        )
        val formats = listOf(audio("en", "English", original = true))
        assertEquals(
            listOf(
                "English", "English (auto)", // original language, written first
                "Deutsch", "español", // written, Latin: German, Spanish
                "العربية", "বাংলা", // written, other scripts: Arabic, Bangla
                "Nederlands (auto)", // automatic, Latin: Dutch
                "العربية (auto)", "日本語 (auto)", // automatic, other scripts: Arabic, Japanese
            ),
            orderCaptions(captions, formats).map { it.label },
        )
    }

    @Test fun `audio goes original, then latin, then other scripts`() {
        val formats = listOf(
            audio("hi", "हिन्दी"),
            audio("fr", "français"),
            audio("ja", "日本語", original = true),
            audio("de", "Deutsch"),
            audio("ar", "العربية"),
        )
        assertEquals(
            listOf("日本語", "français", "Deutsch", "العربية", "हिन्दी"),
            orderAudioFormats(formats).map { it.audioLabel },
        )
    }
}
